public class floatsum {
    public static int sum(int a , int b) {
        return a+b;
    }
    public static float sum(float x , float y) {
        return x+y;
    }
    public static void main(String[] args) {
        System.out.println(sum(12,34));
        System.out.println(sum(23.45f,345.56f));
    }
    
}
